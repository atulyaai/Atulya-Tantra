"""Regenerate requirements.lock.txt from the packages installed in this environment.

Walks the dependency closure of pyproject.toml's runtime dependencies plus the
runtime extras, pins each package to its installed version, and marks packages
needed on only one platform. Run: .venv\\Scripts\\python -m tools.make_lock
"""
from __future__ import annotations

import re
import sys
import tomllib
from importlib.metadata import PackageNotFoundError, distribution
from pathlib import Path

from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parents[1]
EXTRAS = ("voice", "documents", "pc", "mcp", "music")
# Wake word and microphone run on the PC/phone client, never on the Linux server
# (openwakeword would pull tflite-runtime, which has no Python 3.12 wheels).
CLIENT_ONLY = {"openwakeword", "sounddevice"}
PLATFORMS = {
    "win32": {"sys_platform": "win32", "platform_system": "Windows", "os_name": "nt"},
    "linux": {"sys_platform": "linux", "platform_system": "Linux", "os_name": "posix"},
}


def _name(value: str) -> str:
    return re.sub(r"[-_.]+", "-", value).lower()


def _closure(roots: list[Requirement], env: dict) -> set[str]:
    seen: set[str] = set()
    stack = [(req, "") for req in roots]
    while stack:
        req, extra = stack.pop()
        if req.marker and not req.marker.evaluate({**env, "extra": extra}):
            continue
        name = _name(req.name)
        key = name + "[" + ",".join(sorted(req.extras)) + "]"
        if key in seen:
            continue
        seen.add(key)
        try:
            dist = distribution(req.name)
        except PackageNotFoundError:
            continue
        for raw in dist.requires or []:
            child = Requirement(raw)
            for wanted in [""] + sorted(req.extras):
                if child.marker is None or child.marker.evaluate({**env, "extra": wanted}):
                    stack.append((child, wanted))
                    break
    return {key.split("[", 1)[0] for key in seen}


def main() -> int:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    roots = [Requirement(item) for item in project["dependencies"]]
    for extra in EXTRAS:
        roots += [Requirement(item) for item in project["optional-dependencies"][extra]]
    per_platform = {
        plat: _closure([r for r in roots if plat == "win32" or _name(r.name) not in CLIENT_ONLY], env)
        for plat, env in PLATFORMS.items()
    }
    lines = [
        "# Generated by tools/make_lock.py from the installed environment (Python "
        f"{sys.version_info.major}.{sys.version_info.minor}).",
        f"# pyproject dependencies + extras: {', '.join(EXTRAS)}. Do not edit by hand.",
    ]
    missing = []
    for name in sorted(per_platform["win32"] | per_platform["linux"]):
        on_win, on_linux = name in per_platform["win32"], name in per_platform["linux"]
        marker = "" if on_win and on_linux else ('; sys_platform == "win32"' if on_win else '; sys_platform == "linux"')
        try:
            pin = f"{name}=={distribution(name).version}"
        except PackageNotFoundError:
            if on_win:
                missing.append(name)
                continue
            missing.append(f"{name} (linux)")
            continue
        lines.append(pin + marker)
    if missing:
        print(f"Not installed (install, then rerun): {', '.join(missing)}", file=sys.stderr)
        return 1
    (ROOT / "requirements.lock.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(lines) - 2} pins to requirements.lock.txt")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
